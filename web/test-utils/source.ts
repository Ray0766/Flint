// 测试用的源码扫描口径（共享，NEVER 每张卡各写一遍）。
//
// 由来：「源码里不该出现 X」这类断言前后踩了六次同一个坑——**解释自己不做 X 的
// 那句注释被当成做了 X**（SCHEMA-09 / REGION-05 / I18N-06-b / FAV-04 / GRAPH-07 后端
// / GRAPH-08）。每次的修法都一样：先剥注释再扫。抽到这里，是为了让后面的卡
// 直接用同一把尺子，而不是各自再踩一次。
//
// 口径与 `tools/i18n_scan.mjs` 对齐（DEC-008：注释不发给用户）：
// 块注释、整行 `//`、行尾 `//` 都不算代码。比扫描器更严没有意义——
// 严出来的红是假的，而假红会训练人去忽略红。

/** 去掉注释，只留代码。用于「源码里不该出现 X」这类断言。 */
export function codeOnly(source: string): string {
  return source
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.replace(/\/\/.*$/, ""))
    .join("\n");
}
