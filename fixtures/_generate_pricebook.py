def build() -> dict:
    entries = []
    for category, items in CATALOG.items():
        for i, (item, unit, low, high) in enumerate(items, start=1):
            entries.append(
                {
                    "entry_id": f"pe-{category}-{i:02d}",
                    "item": item,
                    "unit": unit,
                    "price_low": low,
                    "price_high": high,
                    "currency": "CNY",
                    "region": "CN",
                    "year": 2026,
                    "source": "seed:2026 调研汇编（生产逐条替换为 url/citation）",
                    "updated_at": "2026-07-01T00:00:00+00:00",
                    "stale_after_months": 12,
                }
            )
    return {"version": 1, "entries": entries}


